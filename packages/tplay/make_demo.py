from pathlib import Path
import struct
r=Path(__file__).resolve().parent
# Original short four-phrase tune, with bass, offbeat harmony, and drum lane.
melody=[72,76,79,76,74,77,81,77,76,79,84,79,74,77,79,71,
        72,76,79,84,81,77,74,77,79,76,72,67,71,74,72,72]
bass=[48,53,57,55,48,53,55,48]
third=[64,65,69,67,64,65,67,64]
events=[(0,bytes([0xff,0x51,3,7,0xa1,0x20])),(0,bytes([0xc0,80])),(0,bytes([0xc1,32])),(0,bytes([0xc2,48]))]
for i,note in enumerate(melody):
 t=i*240
 events.extend([(t,bytes([0x90,note,85])),(t+190,bytes([0x80,note,0])),(t,bytes([0x99,42,48])),(t+40,bytes([0x89,42,0]))])
 if i%2==0:
  n=bass[i//4];events.extend([(t,bytes([0x91,n,80])),(t+420,bytes([0x81,n,0]))])
 if i%2==1:
  n=third[i//4];events.extend([(t,bytes([0x92,n,60])),(t+180,bytes([0x82,n,0]))])
 if i%4==2:events.extend([(t,bytes([0x99,38,72])),(t+80,bytes([0x89,38,0]))])
 if i%4==0:events.extend([(t,bytes([0x99,36,72])),(t+80,bytes([0x89,36,0]))])
def vlq(n):
 b=[n&127];n>>=7
 while n:b.insert(0,(n&127)|128);n>>=7
 return bytes(b)
track=bytearray();last=0
for t,b in sorted(events,key=lambda x:x[0]):track+=vlq(t-last)+b;last=t
track+=vlq(32*240-last)+b'\xff\x2f\0'
data=b'MThd'+struct.pack('>IHHH',6,0,1,480)+b'MTrk'+struct.pack('>I',len(track))+track
(r/'elksbeat.mid').write_bytes(data)
(r/'demo.h').write_text('/* Original ELKS demo melody; generated by make_demo.py. */\nstatic const unsigned char demo_midi[] = {\n'+','.join(str(x) for x in data)+'\n};\n')
